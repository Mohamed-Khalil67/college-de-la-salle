// Copies the shared, dependency-free contracts into the functions codebase so that client and
// server compile against the exact same schema and grading logic. The copy is git-ignored.
const fs = require('node:fs');
const path = require('node:path');

const source = path.resolve(__dirname, '../../libs/contracts/src');
const target = path.resolve(__dirname, '../src/contracts');

fs.rmSync(target, { recursive: true, force: true });
fs.mkdirSync(target, { recursive: true });

for (const file of fs.readdirSync(source)) {
  if (!file.endsWith('.ts') || file.endsWith('.spec.ts')) continue;
  const banner = '// GENERATED by functions/scripts/sync-contracts.cjs — edit libs/contracts instead.\n';
  fs.writeFileSync(path.join(target, file), banner + fs.readFileSync(path.join(source, file), 'utf8'));
}
