// Usage: SCHOOL=<pack> node scripts/select-school.mjs   (default: cdls-daher)
//
// Points the web build at one school pack (schools/<SCHOOL>/, docs/new-school.md). Run before every build, serve,
// test and lint (the npm pre-scripts of apps/web do it). It writes, all gitignored:
//   src/app/core/school/profile.generated.ts   the pack's profile.json, typed SchoolProfile (checked by tsc)
//   src/app/school/active/{index,archive,fr,en,ar}.ts   one-line re-exports of the pack's site/ modules
//   src/generated/index.html                     the page shell (title, theme colour, icons from the profile)
//   src/generated/brand.css                      the profile's colour overrides (empty for none)
//   src/generated/public/                        a copy of the pack's public/ folder (crest, icons, photos)
// When the shared package is built, the profile is also validated with parseSchoolProfile (time zone, sections…).
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const web = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const schools = resolve(web, '../../schools');
const id = (process.env.SCHOOL || 'cdls-daher').trim();

function fail(message) {
  console.error(`select-school: ${message}`);
  process.exit(1);
}

if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(id)) fail(`SCHOOL « ${id} » is not a pack folder name (cdls-daher).`);
const pack = join(schools, id);
const profileFile = join(pack, 'profile.json');
if (!existsSync(profileFile)) fail(`no ${relative(web, profileFile)}. Copy schools/example to start a new school.`);
for (const file of ['index.ts', 'archive.ts', 'fr.ts', 'en.ts', 'ar.ts']) {
  if (!existsSync(join(pack, 'site', file))) fail(`schools/${id}/site/${file} is missing (see schools/example/site).`);
}

const profile = JSON.parse(readFileSync(profileFile, 'utf8'));
if (profile.id !== id) fail(`schools/${id}/profile.json says its id is « ${profile.id} »; they must match.`);
try {
  const shared = await import('@cdls/shared');
  shared.parseSchoolProfile(profile, `schools/${id}/profile.json`);
} catch (error) {
  // Not built yet (a fresh clone running lint): the types still check the shape, the unit tests the rest.
  if (error?.code !== 'ERR_MODULE_NOT_FOUND' && error?.code !== 'ERR_PACKAGE_PATH_NOT_EXPORTED') fail(error.message);
}

/** Writes a file only when its content changes, so the dev server does not rebuild for nothing. */
function write(path, content) {
  mkdirSync(dirname(path), { recursive: true });
  if (existsSync(path) && readFileSync(path, 'utf8') === content) return;
  writeFileSync(path, content);
}

const header = `// Generated by scripts/select-school.mjs for SCHOOL=${id}. Do not edit: change schools/${id}/ instead.\n`;

write(
  join(web, 'src/app/core/school/profile.generated.ts'),
  `${header}import type { SchoolProfile } from '@cdls/shared';\n\nexport const GENERATED_PROFILE: SchoolProfile = ${JSON.stringify(profile, null, 2)};\n`,
);

const activeDir = join(web, 'src/app/school/active');
const toPack = relative(activeDir, join(pack, 'site')).split('\\').join('/');
write(join(activeDir, 'index.ts'), `${header}export { SITE } from '${toPack}/index';\n`);
write(join(activeDir, 'archive.ts'), `${header}export { DIRECTORS, PHOTOS } from '${toPack}/archive';\n`);
for (const lang of ['fr', 'en', 'ar']) {
  write(join(activeDir, `${lang}.ts`), `${header}export { PACK } from '${toPack}/${lang}';\n`);
}

const escape = (text) => text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/"/g, '&quot;');
const names = profile.names.fr;
const icons = profile.brand.icons
  .map((icon) =>
    [
      `<link rel="${icon.rel}"`,
      icon.type ? ` type="${escape(icon.type)}"` : '',
      icon.sizes ? ` sizes="${escape(icon.sizes)}"` : '',
      ` href="${escape(icon.href)}" />`,
    ].join(''),
  )
  .join('\n    ');
const template = readFileSync(join(web, 'src/index.template.html'), 'utf8');
write(
  join(web, 'src/generated/index.html'),
  template
    .replace('{{TITLE}}', escape(`${names.full} — ${names.place}`))
    .replace('{{THEME_COLOR}}', escape(profile.brand.themeColor))
    .replace('{{ICONS}}', icons),
);

const colors = Object.entries(profile.brand.colors)
  .map(([token, value]) => `  ${token}: ${value};`)
  .join('\n');
write(
  join(web, 'src/generated/brand.css'),
  `/* Generated for SCHOOL=${id}: the colour overrides of schools/${id}/profile.json (brand.colors). */\n${colors ? `:root {\n${colors}\n}\n` : ''}`,
);

const publicOut = join(web, 'src/generated/public');
rmSync(publicOut, { recursive: true, force: true });
mkdirSync(publicOut, { recursive: true });
if (existsSync(join(pack, 'public'))) cpSync(join(pack, 'public'), publicOut, { recursive: true });

console.log(`select-school: ${profile.names.fr.full} (${id})`);
